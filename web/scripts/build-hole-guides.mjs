writeFileSync(OUT, header + JSON.stringify(guides, null, 2) + '\n')
console.log(`Wrote ${Object.keys(guides).length} hole guides to src/data/hole-guides.ts`)
if (problems.length) {
  console.log('\nCHECK THESE:')
  for (const p of problems) console.log(' - ' + p)
  process.exitCode = 1
}
