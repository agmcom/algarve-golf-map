// Builds src/data/scorecards.ts from the official scorecards transcribed in
// research/scorecards-2026-11/<slug>.json (format: research/scorecards-2026-11/FORMAT.md).
// Only files with status "found" (an official source) are used. Every card is checked:
// par and metre totals against the totals printed on the card, and stroke indexes.
//
// Usage (from web/): node scripts/build-scorecards.mjs

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const RESEARCH = join(here, '..', '..', 'research', 'scorecards-2026-11')
const OUT = join(here, '..', 'src', 'data', 'scorecards.ts')

const problems = []
const cards = {}

// Official cards we hold back, with the reason. Revisit when the club publishes a new card.
const EXCLUDE = {
  'monte-rei': 'Card dated March 2026, before the April–September 2026 renovation that changed the tees.',
  'benamor': 'Official page gives distances to the FRONT of the green, not hole lengths; also contradicts itself on hole 16 stroke index.',
  'san-lorenzo': 'Closed for renovation until 2028; the only card is from 2011.',
}

// Display names for tees, where the card prints no name or a code. The FPG's names for the same
// tees are used (research/fpg_course_ratings_2026-11.tsv), so the scorecard and slope pages match.
const TEE_NAMES = {
  'vila-sol': { 'Light grey': 'White' },
  'castro-marim': { 'Trophy': 'White' },
  'boavista': { 'Champ': 'Black', 'Comp': 'White', 'Mens': 'Yellow', 'Ladies': 'Red' },
  'ombria': { '58': 'Tee 58', '53': 'Tee 53', '49': 'Tee 49', '45': 'Tee 45' },
}

// Stroke indexes we drop because the official source is internally inconsistent.
const DROP_SI = {
  'vale-do-lobo-ocean': 'The official course page gives stroke index 12 to both holes 11 and 15 and none to 2, so stroke indexes are not shown.',
}

for (const file of readdirSync(RESEARCH).filter(f => f.endsWith('.json')).sort()) {
  const d = JSON.parse(readFileSync(join(RESEARCH, file), 'utf8'))
  if (d.status !== 'found') continue
  const slug = d.slug
  if (EXCLUDE[slug]) { console.log(`held back: ${slug} — ${EXCLUDE[slug]}`); continue }
  const names = TEE_NAMES[slug] ?? {}
  const tees = d.tees.map(t => names[t] ?? t)
  const rename = Object.fromEntries(d.tees.map((t, i) => [t, tees[i]]))
  const dropSi = !!DROP_SI[slug]
  const yards = d.unit === 'yards'

  const loops = d.loops.map(l => ({
    name: l.name ?? null,
    holes: l.holes.map(h => {
      const m = {}
      for (const [k, v] of Object.entries(h.m ?? {})) {
        if (v == null) continue
        m[rename[k] ?? k] = yards ? Math.round(v * 0.9144) : v
      }
      return {
        n: h.n, par: h.par, parLadies: h.par_ladies ?? null,
        si: dropSi ? null : (h.si ?? null), siLadies: dropSi ? null : (h.si_ladies ?? null), m,
      }
    }),
  }))

  // Checks
  for (const l of loops) {
    if (l.holes.some(h => ![3, 4, 5, 6].includes(h.par))) problems.push(`${slug}: odd par value`)
  }
  const holes = loops.flatMap(l => l.holes)
  if (loops.length === 1 && holes.length === 18) {
    const si = holes.map(h => h.si).filter(x => x != null)
    if (si.length === 18 && new Set(si).size !== 18) problems.push(`${slug}: stroke index repeated`)
  }
  // Totals: either { tee: n } for the whole card, or { loopName: { tee: n } } per loop.
  const checks = []
  for (const [k, v] of Object.entries(d.totals_on_card ?? {})) {
    if (typeof v === 'number') checks.push([k, v, holes])
    else if (v && typeof v === 'object') {
      const loop = loops.find(l => l.name === k)
      if (!loop) continue
      for (const [tee, n] of Object.entries(v)) if (typeof n === 'number' && tee !== 'par') checks.push([tee, n, loop.holes])
    }
  }
  for (const [tee, printed, hs] of checks) {
    const t = rename[tee] ?? tee
    const vals = hs.map(h => h.m[t])
    if (vals.some(v => v == null)) continue
    let sum = vals.reduce((a, b) => a + b, 0)
    const printedM = yards ? Math.round(printed * 0.9144) : printed
    if (Math.abs(sum - printedM) > (yards ? hs.length : 1)) problems.push(`${slug}: ${t} sums to ${sum} m, card says ${printedM}`)
  }

  cards[slug] = {
    tees,
    loops,
    // Public wording; the research JSON's own label is a note for us, not for readers.
    source: { label: { pdf: 'official scorecard (PDF)', image: 'official scorecard', webpage: 'official hole-by-hole course page' }[d.source.type] ?? 'official scorecard', url: d.source.url },
    checked: d.checked,
    convertedFromYards: yards,
    notes: [...(DROP_SI[slug] ? [DROP_SI[slug]] : [])],
  }
}

const header = `// Official scorecards, transcribed from each club's own card (PDF, image or official
// hole-by-hole page). Generated by scripts/build-scorecards.mjs from research/scorecards-2026-11/.
// Do not edit by hand: fix the research JSON and run the script again.

export interface ScorecardHole {
  n: number
  par: number
  parLadies: number | null
  si: number | null       // stroke index (men, or the only one printed)
  siLadies: number | null
  m: Record<string, number> // metres from each tee
}
export interface ScorecardLoop { name: string | null; holes: ScorecardHole[] }
export interface Scorecard {
  tees: string[]          // longest to shortest
  loops: ScorecardLoop[]  // one loop of 18, or loops of 9 on 9- and 27-hole courses
  source: { label: string; url: string }
  checked: string         // ISO date the card was transcribed
  convertedFromYards: boolean
  notes: string[]
}

export const SCORECARDS: Record<string, Scorecard> = `

writeFileSync(OUT, header + JSON.stringify(cards, null, 2) + '\n')
console.log(`Wrote ${Object.keys(cards).length} scorecards to src/data/scorecards.ts`)
if (problems.length) {
  console.log('\nCHECK THESE:')
  for (const p of problems) console.log(' - ' + p)
  process.exitCode = 1
}
