// Writes src/data/faroDriveTimes.ts: real road times from Faro Airport to every course (Mapbox).
// Re-run when a course is added or moved: node scripts/build-faro-drive-times.mjs
import { readFileSync, writeFileSync } from 'fs'
const env = Object.fromEntries(readFileSync('.env.local','utf-8').split('\n').filter(l=>l.includes('=')&&!l.startsWith('#')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1)]}))
const { createClient } = await import('@supabase/supabase-js')
const supabase = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY)

// A point on the airport access road by the terminal. The airport's reference coordinates snap
// inside the airfield and add 12-15 minutes to every route.
const ORIGIN = '-7.9660,37.0215'

const { data: courses, error } = await supabase.from('courses').select('slug,lat,lng').order('slug')
if (error) throw error

const lines = []
for (const c of courses) {
  const url = `https://api.mapbox.com/directions/v5/mapbox/driving/${ORIGIN};${c.lng},${c.lat}?access_token=${env.NEXT_PUBLIC_MAPBOX_TOKEN}&overview=false`
  const route = (await (await fetch(url)).json()).routes?.[0]
  if (!route) throw new Error(`No route for ${c.slug}`)
  const km = Math.round(route.distance / 1000)
  const mins = Math.round(route.duration / 60 / 5) * 5
  lines.push(`  { slug: '${c.slug}', lat: ${c.lat}, lng: ${c.lng}, km: ${km}, mins: ${mins} },`)
}

writeFileSync('src/data/faroDriveTimes.ts', `// Generated by scripts/build-faro-drive-times.mjs. Road distance and drive time from Faro Airport
// to each course without traffic, minutes rounded to the nearest 5.
export const FARO_DRIVE_TIMES: { slug: string; lat: number; lng: number; km: number; mins: number }[] = [
${lines.join('\n')}
]
`)
console.log(`Wrote ${lines.length} courses`)
